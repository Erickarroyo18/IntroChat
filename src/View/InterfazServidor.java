    // Método para manejar el evento del filtro de tipo de paquete
    private void filtroTipoActionPerformed(java.awt.event.ActionEvent evt) {
        String selectedFilter = (String) filtroTipo.getSelectedItem();
        StyledDocument doc = acciones.getStyledDocument();
        acciones.setText(""); // Limpiar el JTextPane

        try {
            if ("Todos".equals(selectedFilter)) {
                // Restaurar el estado original de los mensajes
                doc.insertString(0, mensajesOriginales.toString().replace("//", ""), null);
            } else {
                // Filtrar los mensajes que contengan el tipo de paquete seleccionado
                String[] mensajes = mensajesOriginales.toString().split("//");
                for (String mensaje : mensajes) {
                    mensaje = (mensaje.trim().isEmpty()) ? null : mensaje;
                    if (mensaje != null && mensaje.contains(selectedFilter)) {
                        doc.insertString(doc.getLength(), removerContenidoEnCorchetes(mensaje) + "\n", null);
                    }
                }
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    /**
     * Metodo para remover el contenido en corchetes desde el inicio de una cadena
     *
     * @param mensaje El mensaje a procesar
     * @return El mensaje sin el contenido en corchetes
     */
    public String removerContenidoEnCorchetes(String mensaje) {
        return mensaje.replaceAll("^\\[.*?\\]\\s*", "");
    }

    /**
     * Metodo para agregar mensajes y almacenarlos
     *
     * @param mensaje El mensaje a agregar
     */
    public void agregarMensaje(String mensaje, Color color) {
        StyledDocument doc = acciones.getStyledDocument();

        // Crear un conjunto de atributos para el color del texto
        SimpleAttributeSet attributeSet = new SimpleAttributeSet();
        StyleConstants.setForeground(attributeSet, color);

        try {
            // Insertar el texto con el color especificado
            doc.insertString(doc.getLength(), mensaje + "\n", attributeSet);
            // Guardar el mensaje original en el StringBuilder
            mensaje = String.format("// %s // ", mensaje);
            mensajesOriginales.append(mensaje).append("\n");
        } catch (Exception e) {
            e.printStackTrace();
        }

    }

